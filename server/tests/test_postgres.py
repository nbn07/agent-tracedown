# ----------------------------------------------------------------------------- translation (no database)

def test_translate_placeholders_null_safe_equality_and_literals():
    assert translate_sql("SELECT * FROM t WHERE a=? AND b IS ? AND c LIKE 'x%?y'") == \
        "SELECT * FROM t WHERE a=%s AND b IS NOT DISTINCT FROM %s AND c LIKE 'x%%?y'"
    assert translate_sql("SELECT 'it''s ?' AS s, ? AS v") == "SELECT 'it''s ?' AS s, %s AS v"


def test_translate_insert_or_ignore_and_reject_or_replace():
    assert translate_sql("INSERT OR IGNORE INTO t(a) VALUES (?)") == "INSERT INTO t(a) VALUES (%s) ON CONFLICT DO NOTHING"
    with pytest.raises(ValueError):
        translate_sql("INSERT OR REPLACE INTO t VALUES (?)")


def test_translate_ddl_types():
    ddl = translate_ddl("CREATE TABLE IF NOT EXISTS x (id INTEGER PRIMARY KEY AUTOINCREMENT, at INTEGER, v REAL, b BLOB)")
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl and "at BIGINT" in ddl
    assert "v DOUBLE PRECISION" in ddl and "b BYTEA" in ddl


def test_no_module_writes_non_portable_sql():
    """Every feature module's SQL must run on both SQLite and Postgres."""
    import re
    base = os.path.join(ROOT, "server", "tracedown_server")
    bad = []
    for dirpath, _, files in os.walk(base):
        for f in files:
            if not f.endswith(".py") or f in ("postgres.py",) or "clickhouse" in f:
                continue
            path = os.path.join(dirpath, f)
            src = open(path).read()
            if os.path.basename(dirpath) == "storage" and f == "__init__.py":
                continue  # the SQLite store itself
            for pat in (r"INSERT OR REPLACE", r"json_extract", r"\bMAX\([^)]*,\s*\?", r"SUM\(\w+\s*="):
                for m in re.finditer(pat, src):
                    line = src[:m.start()].count("\n") + 1
                    bad.append(f"{os.path.relpath(path, base)}:{line}: {m.group(0)}")
    assert not bad, bad


