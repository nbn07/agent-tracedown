@needs_pg
def test_full_run_round_trip_on_postgres(pg):
    store = pg()
    mem = tdn.MemoryExporter()
    tdn.init(project="demo", exporter=mem)
    try:
        demo.calendar_agent()
    except tdn.ToolError:
        pass
    store.put_blobs(mem.blobs, "demo")
    store.put_spans("demo", mem.spans)
    tid = mem.spans[0]["trace_id"]
    run = store.get_run(tid)
    assert run["outcome"] == "failure" and run["models"] == ["gpt-4o-mini"] and isinstance(run["attributes"], dict)
    spans = store.get_spans(tid)
    assert len(spans) == len(mem.spans) and all(isinstance(s["attributes"], dict) for s in spans)
    assert store.get_blobs([s["input_digest"] for s in spans], "demo")
    assert store.tool_stats("demo")[0]["tool"] == "calendar_create_event"
    st = store.stats("demo")["agents"][0]
    assert st["runs"] == 1 and st["failures"] == 1 and isinstance(st["input_tokens"], int)
    store.set_profile(tid, {"dims": {"model": "m"}})
    assert store.run_profiles(project="demo")[0]["profile"]["dims"]["model"] == "m"
    # same trace from another project is refused, exactly as on SQLite
    from tracedown_server.storage import TraceOwnershipError
    with pytest.raises(TraceOwnershipError):
        store.put_spans("other", mem.spans)


@needs_pg
def test_audit_chain_stays_valid_with_two_replicas_writing_at_once(pg):
    from tracedown_server.enterprise.audit import AuditLog
    logs = [AuditLog(pg()), AuditLog(pg())]  # two processes' worth of stores, one database

    def write(log, i):
        for j in range(15):
            log.append(f"user{i}", "read", f"run-{j}")
    threads = [threading.Thread(target=write, args=(logs[i % 2], i)) for i in range(4)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    assert len(logs[0].export()) == 60
    assert logs[1].verify()["ok"] is True


@needs_pg
def test_app_on_postgres_via_environment(monkeypatch):
    import psycopg
    schema = "t_" + uuid.uuid4().hex[:16]
    with psycopg.connect(URL, autocommit=True) as c:
        c.execute(f'CREATE SCHEMA "{schema}"')
    sep = "&" if "?" in URL else "?"
    monkeypatch.setenv("TDN_DATABASE_URL", f"{URL}{sep}options=-csearch_path%3D{schema}")
    monkeypatch.delenv("TDN_CLICKHOUSE", raising=False)
    from tracedown_server.api import create_app
    from tracedown_server.cache import unwrap
    from tracedown_server.storage.postgres import PostgresStore
    app = create_app(api_keys=[], queue=False, cache=None)
    store = unwrap(app.state.store)
    try:
        assert isinstance(store, PostgresStore)
        c = TestClient(app)
        mem = tdn.MemoryExporter()
        tdn.init(project="demo", exporter=mem)
        try:
            demo.calendar_agent()
        except tdn.ToolError:
            pass
        c.post("/v1/ingest/blobs", json={"project": "demo", "blobs": mem.blobs})
        assert c.post("/v1/ingest/spans", json={"project": "demo", "spans": mem.spans}).status_code == 200
        runs = c.get("/api/v1/runs?project=demo").json()["runs"]
        assert runs[0]["root_cause"]["category"] == "bad_llm_output"
        assert c.get("/api/v1/incidents").json()["incidents"]
    finally:
        store.close()
        with psycopg.connect(URL, autocommit=True) as c2:
            c2.execute(f'DROP SCHEMA "{schema}" CASCADE')


@needs_pg
def test_postgres_metadata_with_clickhouse_spans(pg):
    pytest.importorskip("chdb")
    from tracedown_server.enterprise import postgres_hybrid
    from tracedown_server.enterprise.clickhouse import ChdbClient, ClusterRouter
    client = ChdbClient()
    db = "tdn_pg_" + uuid.uuid4().hex[:8]
    router = ClusterRouter({"clusters": {"main": {"database": db}}, "default": "main"},
                           client_factory=lambda cfg: client)
    pg_store = pg()  # creates the schema
    store = postgres_hybrid(URL, router, schema=pg_store.schema)
    try:
        mem = tdn.MemoryExporter()
        tdn.init(project="demo", exporter=mem)
        try:
            demo.calendar_agent()
        except tdn.ToolError:
            pass
        store.put_spans("demo", mem.spans)
        tid = mem.spans[0]["trace_id"]
        assert client.query(f"SELECT count() n FROM {db}.spans WHERE trace_id='{tid}'")[0]["n"] == len(mem.spans)
        assert store.query("SELECT COUNT(*) n FROM spans")[0]["n"] == 0      # spans are not in Postgres
        assert store.get_run(tid)["outcome"] == "failure"                   # the run index is
        assert len(store.get_spans(tid)) == len(mem.spans)
    finally:
        store.close()


@needs_pg
def test_nul_characters_are_stored_safely(pg):
    pg_store = pg()
    """Postgres refuses NUL in text and JSONB; an agent output containing one must still be stored."""
    import agent_tracedown as tdn
    mem = tdn.MemoryExporter()
    tdn.init(project="p", exporter=mem)
    with tdn.run("Bot\x00", input="a\x00b") as run:
        tdn.tool_call("t", {"a": "x\x00y"}, lambda a: "out\x00put")
        run.fail("broke\x00here")
    pg_store.put_blobs(mem.blobs, "p")
    assert pg_store.put_spans("p", mem.trace(run.trace_id)) == 2
    spans = pg_store.get_spans(run.trace_id)
    assert len(spans) == 2 and all("\x00" not in s["status"]["message"] for s in spans)
    assert pg_store.get_blobs(list(mem.blobs), "p") == mem.blobs   # payloads keep their exact digest
