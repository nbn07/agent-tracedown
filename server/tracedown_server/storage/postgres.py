"""Postgres metadata store: the production drop-in for ``SQLiteStore``.

Select it with ``TDN_DATABASE_URL=postgresql://user:pass@host:5432/db``. Every public method
of ``SQLiteStore`` behaves the same, and the generic ``execute`` / ``query`` / ``ensure_schema``
that feature modules (incidents, drift, audit, RBAC, PII, hooks, settings) use accept the
same SQL: a small translation layer maps the SQLite dialect those modules write to Postgres.

Uses psycopg 3 with a connection pool, so it is safe across threads and server workers.
Large span volumes belong in ClickHouse (``TDN_CLICKHOUSE``); this store then holds the
run index, findings, payloads and everything users create.
"""
from __future__ import annotations

import json
import re
import threading
from decimal import Decimal
from typing import Any, Dict, Iterable, List, Optional

from . import TraceOwnershipError, _tool_row

SCHEMA_VERSION = 1

# Core tables. JSON columns are JSONB; nanosecond timestamps need BIGINT.
CORE_SCHEMA = """
CREATE TABLE IF NOT EXISTS schema_migrations (
    version     INTEGER PRIMARY KEY,
    applied_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    note        TEXT
);
CREATE TABLE IF NOT EXISTS runs (
    trace_id      TEXT PRIMARY KEY,
    project       TEXT NOT NULL,
    agent_name    TEXT,
    outcome       TEXT,
    error         TEXT,
    started_at    BIGINT,
    duration_ms   DOUBLE PRECISION,
    span_count    INTEGER,
    input_tokens  BIGINT,
    output_tokens BIGINT,
    models        JSONB,
    replay_of     TEXT,
    attributes    JSONB,
    profile       JSONB
);
CREATE INDEX IF NOT EXISTS runs_project_time ON runs(project, started_at DESC);
CREATE INDEX IF NOT EXISTS runs_agent_time ON runs(agent_name, started_at);
CREATE TABLE IF NOT EXISTS spans (
    project        TEXT NOT NULL,
    trace_id       TEXT NOT NULL,
    span_id        TEXT NOT NULL,
    parent_span_id TEXT,
    name           TEXT,
    kind           TEXT,
    start_time     BIGINT,
    end_time       BIGINT,
    status_code    TEXT,
    status_message TEXT,
    attributes     JSONB,
    input_digest   TEXT,
    output_digest  TEXT,
    PRIMARY KEY (trace_id, span_id)
);
CREATE INDEX IF NOT EXISTS spans_project_kind ON spans(project, kind, start_time);
CREATE TABLE IF NOT EXISTS payloads (
    project  TEXT NOT NULL,
    digest   TEXT NOT NULL,
    content  TEXT NOT NULL,
    PRIMARY KEY (project, digest)
);
CREATE TABLE IF NOT EXISTS trace_owner (
    trace_id  TEXT PRIMARY KEY,
    project   TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS findings (
    trace_id   TEXT PRIMARY KEY,
    report     JSONB NOT NULL,
    created_at BIGINT
);
"""

# ----------------------------------------------------------------------------- dialect translation

_DDL_RULES = [
    (re.compile(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", re.I), "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
    (re.compile(r"\bINTEGER\b", re.I), "BIGINT"),
    (re.compile(r"\bREAL\b", re.I), "DOUBLE PRECISION"),
    (re.compile(r"\bBLOB\b", re.I), "BYTEA"),
]
_IDENTITY_COL = re.compile(r"CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+(\w+)\s*\(\s*(\w+)\s+INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT",
                           re.I)


def translate_ddl(ddl: str) -> str:
    """SQLite DDL as the feature modules write it -> Postgres DDL."""
    for rx, repl in _DDL_RULES:
        ddl = rx.sub(repl, ddl)
    return ddl


def _split_quoted(sql: str):
    """Yield (is_literal, text) chunks so rewrites never touch string literals."""
    out, buf, i, q = [], [], 0, None
    while i < len(sql):
        ch = sql[i]
        if q:
            buf.append(ch)
            if ch == q:
                if i + 1 < len(sql) and sql[i + 1] == q:  # escaped quote
                    buf.append(sql[i + 1])
                    i += 1
                else:
                    out.append((True, "".join(buf)))
                    buf, q = [], None
        elif ch in ("'", '"'):
            if buf:
                out.append((False, "".join(buf)))
            buf, q = [ch], ch
        else:
            buf.append(ch)
        i += 1
    if buf:
        out.append((bool(q), "".join(buf)))
    return out


_INSERT_OR_IGNORE = re.compile(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO", re.I)
_IS_PARAM = re.compile(r"\bIS\s+\?", re.I)


def translate_sql(sql: str) -> str:
    """SQLite-dialect statement -> Postgres: ``?`` -> ``%s``, ``IS ?`` -> ``IS NOT DISTINCT FROM``,
    ``INSERT OR IGNORE`` -> ``ON CONFLICT DO NOTHING``; ``%`` is escaped for psycopg."""
    ignore = bool(_INSERT_OR_IGNORE.match(sql))
    if ignore:
        sql = _INSERT_OR_IGNORE.sub("INSERT INTO", sql, count=1)
    if re.match(r"^\s*INSERT\s+OR\s+REPLACE", sql, re.I):
        raise ValueError("INSERT OR REPLACE is not portable; write INSERT ... ON CONFLICT(...) DO UPDATE")
    parts = []
    for literal, text in _split_quoted(sql):
        if literal:
            parts.append(text.replace("%", "%%"))
        else:
            text = _IS_PARAM.sub("IS NOT DISTINCT FROM ?", text)
            parts.append(text.replace("%", "%%").replace("?", "%s"))
    out = "".join(parts)
    if ignore and "ON CONFLICT" not in out.upper():
        out = out.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return out


def _plain(v: Any) -> Any:
    if isinstance(v, Decimal):
        return int(v) if v == v.to_integral_value() else float(v)
    return v


# ----------------------------------------------------------------------------- the store

class PostgresStore:
    """Same interface as ``SQLiteStore``, on Postgres."""

    dialect = "postgres"

    def __init__(self, url: str, schema: Optional[str] = None, min_size: int = 1, max_size: int = 10) -> None:
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool
        import psycopg

        self.url = url
        self.schema = schema
        if schema:  # an isolated namespace (tests, multi-tenant installs)
            if not re.fullmatch(r"[a-z_][a-z0-9_]{0,62}", schema):
                raise ValueError("schema must be a lowercase identifier")
            with psycopg.connect(url, autocommit=True) as c:
                c.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
        kwargs: Dict[str, Any] = {"row_factory": dict_row}
        if schema:
            kwargs["options"] = f"-c search_path={schema}"
        self._pool = ConnectionPool(url, min_size=min_size, max_size=max_size, kwargs=kwargs, open=True,
                                    name="tracedown")
        self._identity: Dict[str, str] = {}  # table -> identity column, for lastrowid
        self._lock = threading.Lock()
        self._migrate()

    def close(self) -> None:
        self._pool.close()

    def serial_lock(self, name: str) -> "_AdvisoryLock":
        """A lock that serializes a critical section across every process using this database."""
        return _AdvisoryLock(self, name)

    # ------------------------------------------------------------------ migrations
    def _migrate(self) -> None:
        with self._pool.connection() as c:
            # one installer at a time when several replicas start together
            c.execute("SELECT pg_advisory_xact_lock(7262001)")
            c.execute(CORE_SCHEMA)
            done = {r["version"] for r in c.execute("SELECT version FROM schema_migrations").fetchall()}
            if 1 not in done:
                c.execute("INSERT INTO schema_migrations(version, note) VALUES (1, 'core tables') "
                          "ON CONFLICT DO NOTHING")

    def schema_version(self) -> int:
        rows = self.query("SELECT MAX(version) v FROM schema_migrations")
        return rows[0]["v"] or 0

    # ------------------------------------------------------------------ generic access for feature modules
    def ensure_schema(self, ddl: str) -> None:
        for table, col in _IDENTITY_COL.findall(ddl):
            self._identity[table.lower()] = col
        with self._pool.connection() as c:
            c.execute("SELECT pg_advisory_xact_lock(7262001)")
            c.execute(translate_ddl(ddl))

    def _returning(self, sql: str) -> Optional[str]:
        m = re.match(r"^\s*INSERT\s+(?:OR\s+\w+\s+)?INTO\s+(\w+)", sql, re.I)
        if m and "RETURNING" not in sql.upper():
            return self._identity.get(m.group(1).lower())
        return None

    def execute(self, sql: str, args: Iterable[Any] = ()) -> Optional[int]:
        """Run one statement; for an INSERT into a table with an identity column, return the new id."""
        col = self._returning(sql)
        pg = translate_sql(sql)
        args = [_txt(a) for a in args]
        if col:
            pg += f" RETURNING {col}"
        with self._pool.connection() as c:
            cur = c.execute(pg, tuple(args))
            if col:
                row = cur.fetchone()
                return row[col] if row else None
        return None

    def query(self, sql: str, args: Iterable[Any] = ()) -> List[Dict[str, Any]]:
        with self._pool.connection() as c:
            rows = c.execute(translate_sql(sql), tuple(args)).fetchall()
        return [{k: _plain(v) for k, v in r.items()} for r in rows]

    # ------------------------------------------------------------------ writes
    def put_blobs(self, blobs: Dict[str, str], project: str = "default") -> int:
        if blobs:
            with self._pool.connection() as c, c.cursor() as cur:
                cur.executemany("INSERT INTO payloads(project, digest, content) VALUES (%s, %s, %s) "
                                "ON CONFLICT DO NOTHING", [(project, d, txt) for d, txt in blobs.items()])
        return len(blobs)

    def claim_traces(self, project: str, trace_ids: Iterable[str]) -> List[str]:
        ids = sorted(set(trace_ids))
        if not ids:
            return []
        with self._pool.connection() as c, c.cursor() as cur:
            cur.executemany("INSERT INTO trace_owner(trace_id, project) VALUES (%s, %s) ON CONFLICT DO NOTHING",
                            [(t, project) for t in ids])
            rows = cur.execute("SELECT trace_id, project FROM trace_owner WHERE trace_id = ANY(%s)", (ids,)).fetchall()
        return [r["trace_id"] for r in rows if r["project"] != project]

    def check_ownership(self, project: str, spans: List[Dict[str, Any]]) -> None:
        taken = self.claim_traces(project, (sp["trace_id"] for sp in spans))
        if taken:
            raise TraceOwnershipError(f"trace(s) {', '.join(t[:8] for t in taken)} belong to another project")

    def trace_project(self, trace_id: str) -> Optional[str]:
        rows = self.query("SELECT project FROM trace_owner WHERE trace_id=?", (trace_id,))
        return rows[0]["project"] if rows else None

    def put_spans(self, project: str, spans: Iterable[Dict[str, Any]]) -> int:
        from psycopg.types.json import Jsonb
        spans = list(spans)
        self.check_ownership(project, spans)
        rows = [(
            project, s["trace_id"], s["span_id"], s.get("parent_span_id"), _txt(s["name"]), s["kind"],
            s["start_time"], s.get("end_time"), s.get("status", {}).get("code", "UNSET"),
            _txt(s.get("status", {}).get("message", "")), Jsonb(_json_safe(s.get("attributes", {}))),
            s.get("input_digest"), s.get("output_digest"),
        ) for s in spans]
        with self._pool.connection() as c, c.cursor() as cur:
            cur.executemany(
                "INSERT INTO spans VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) "
                "ON CONFLICT (trace_id, span_id) DO UPDATE SET project=excluded.project, "
                "parent_span_id=excluded.parent_span_id, name=excluded.name, kind=excluded.kind, "
                "start_time=excluded.start_time, end_time=excluded.end_time, status_code=excluded.status_code, "
                "status_message=excluded.status_message, attributes=excluded.attributes, "
                "input_digest=excluded.input_digest, output_digest=excluded.output_digest", rows)
        for trace_id in {r[1] for r in rows}:
            self._refresh_run(project, trace_id)
        return len(rows)

    def _refresh_run(self, project: str, trace_id: str) -> None:
        from psycopg.types.json import Jsonb
        spans = self.get_spans(trace_id)
        roots = [s for s in spans if not s["parent_span_id"]]
        if not roots:
            return
        root = roots[0]
        a = root["attributes"]
        llm = [s for s in spans if s["kind"] == "llm"]
        tokens_in = sum(int(s["attributes"].get("gen_ai.usage.input_tokens") or 0) for s in llm)
        tokens_out = sum(int(s["attributes"].get("gen_ai.usage.output_tokens") or 0) for s in llm)
        models = sorted({s["attributes"].get("gen_ai.request.model") for s in llm} - {None})
        errors = [s for s in spans if s["status"]["code"] == "ERROR"]
        outcome = a.get("tdn.run.outcome") or ("failure" if errors else "success")
        first_err = root["status"]["message"] or (errors[0]["status"]["message"] if errors else None)
        duration = ((root["end_time"] or root["start_time"]) - root["start_time"]) / 1e6
        with self._pool.connection() as c:
            c.execute(
                "INSERT INTO runs(trace_id, project, agent_name, outcome, error, started_at, duration_ms, span_count, "
                "input_tokens, output_tokens, models, replay_of, attributes) "
                "VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) "
                "ON CONFLICT (trace_id) DO UPDATE SET project=excluded.project, agent_name=excluded.agent_name, "
                "outcome=excluded.outcome, error=excluded.error, started_at=excluded.started_at, "
                "duration_ms=excluded.duration_ms, span_count=excluded.span_count, "
                "input_tokens=excluded.input_tokens, output_tokens=excluded.output_tokens, models=excluded.models, "
                "replay_of=excluded.replay_of, attributes=excluded.attributes",
                (trace_id, project, a.get("gen_ai.agent.name", root["name"]), outcome, first_err, root["start_time"],
                 duration, len(spans), tokens_in, tokens_out, Jsonb(models), a.get("tdn.replay.of"),
                 Jsonb(_json_safe(a))))

    def set_profile(self, trace_id: str, profile: Dict[str, Any]) -> None:
        from psycopg.types.json import Jsonb
        with self._pool.connection() as c:
            c.execute("UPDATE runs SET profile=%s WHERE trace_id=%s", (Jsonb(_json_safe(profile)), trace_id))

    def run_profiles(self, agent: Optional[str] = None, project: Optional[str] = None,
                     since_ns: Optional[int] = None) -> List[Dict[str, Any]]:
        q, args = ("SELECT trace_id, project, agent_name, outcome, started_at, profile FROM runs "
                   "WHERE profile IS NOT NULL AND replay_of IS NULL"), []
        for col, val in (("agent_name", agent), ("project", project)):
            if val:
                q += f" AND {col}=?"
                args.append(val)
        if since_ns:
            q += " AND started_at>=?"
            args.append(since_ns)
        rows = self.query(q + " ORDER BY started_at", args)
        for r in rows:
            r["profile"] = _loads(r["profile"])
        return rows

    def put_findings(self, trace_id: str, report: Dict[str, Any], created_at: int) -> None:
        from psycopg.types.json import Jsonb
        with self._pool.connection() as c:
            c.execute("INSERT INTO findings(trace_id, report, created_at) VALUES (%s,%s,%s) "
                      "ON CONFLICT (trace_id) DO UPDATE SET report=excluded.report, created_at=excluded.created_at",
                      (trace_id, Jsonb(_json_safe(report)), created_at))

    # ------------------------------------------------------------------ reads
    @staticmethod
    def _span_row(r: Dict[str, Any]) -> Dict[str, Any]:
        return {
            "trace_id": r["trace_id"], "span_id": r["span_id"], "parent_span_id": r["parent_span_id"],
            "name": r["name"], "kind": r["kind"], "start_time": r["start_time"], "end_time": r["end_time"],
            "status": {"code": r["status_code"], "message": r["status_message"]},
            "attributes": _loads(r["attributes"]) or {},
            "input_digest": r["input_digest"], "output_digest": r["output_digest"],
        }

    @staticmethod
    def _run_row(r: Dict[str, Any]) -> Dict[str, Any]:
        d = {k: _plain(v) for k, v in r.items()}
        d["models"] = _loads(d["models"]) or []
        d["attributes"] = _loads(d["attributes"]) or {}
        d["profile"] = _loads(d["profile"]) if d.get("profile") is not None else None
        return d

    def get_spans(self, trace_id: str) -> List[Dict[str, Any]]:
        with self._pool.connection() as c:
            rows = c.execute("SELECT * FROM spans WHERE trace_id=%s ORDER BY start_time, span_id", (trace_id,)).fetchall()
        return [self._span_row(r) for r in rows]

    def get_run(self, trace_id: str) -> Optional[Dict[str, Any]]:
        with self._pool.connection() as c:
            r = c.execute("SELECT * FROM runs WHERE trace_id=%s", (trace_id,)).fetchone()
        return self._run_row(r) if r else None

    def list_runs(self, project: Optional[str] = None, agent: Optional[str] = None,
                  outcome: Optional[str] = None, limit: int = 50, offset: int = 0) -> List[Dict[str, Any]]:
        q, args = "SELECT * FROM runs WHERE 1=1", []
        for col, val in (("project", project), ("agent_name", agent), ("outcome", outcome)):
            if val:
                q += f" AND {col}=%s"
                args.append(val)
        q += " ORDER BY started_at DESC LIMIT %s OFFSET %s"
        args += [limit, offset]
        with self._pool.connection() as c:
            rows = c.execute(q, args).fetchall()
        return [self._run_row(r) for r in rows]

    def get_blobs(self, digests: Iterable[str], project: str = "default") -> Dict[str, str]:
        digests = [d for d in set(digests) if d]
        if not digests:
            return {}
        with self._pool.connection() as c:
            rows = c.execute("SELECT digest, content FROM payloads WHERE project=%s AND digest = ANY(%s)",
                             (project, digests)).fetchall()
        return {r["digest"]: r["content"] for r in rows}

    def get_findings(self, trace_id: str) -> Optional[Dict[str, Any]]:
        with self._pool.connection() as c:
            r = c.execute("SELECT report FROM findings WHERE trace_id=%s", (trace_id,)).fetchone()
        return _loads(r["report"]) if r else None

    def tool_stats(self, project: Optional[str] = None, since_ns: Optional[int] = None) -> List[Dict[str, Any]]:
        q = ("SELECT attributes->>'gen_ai.tool.name' AS tool, status_code, "
             "(COALESCE(end_time, start_time) - start_time) / 1e6 AS ms FROM spans WHERE kind='tool'")
        args: list = []
        if project:
            q += " AND project=%s"
            args.append(project)
        if since_ns:
            q += " AND start_time>=%s"
            args.append(since_ns)
        with self._pool.connection() as c:
            rows = c.execute(q, args).fetchall()
        groups: Dict[str, List[Dict[str, Any]]] = {}
        for r in rows:
            groups.setdefault(r["tool"] or "unknown", []).append(r)
        return [_tool_row(tool, [float(r["ms"]) for r in rs], sum(r["status_code"] == "ERROR" for r in rs))
                for tool, rs in sorted(groups.items(), key=lambda kv: -len(kv[1]))]

    def stats(self, project: Optional[str] = None) -> Dict[str, Any]:
        q = ("SELECT agent_name, COUNT(*) n, SUM(CASE WHEN outcome='failure' THEN 1 ELSE 0 END) failures, "
             "AVG(duration_ms) avg_ms, SUM(input_tokens) tin, SUM(output_tokens) tout FROM runs")
        args: list = []
        if project:
            q += " WHERE project=%s"
            args.append(project)
        q += " GROUP BY agent_name ORDER BY n DESC"
        with self._pool.connection() as c:
            rows = [{k: _plain(v) for k, v in r.items()} for r in c.execute(q, args).fetchall()]
        return {"agents": [{
            "agent": r["agent_name"], "runs": r["n"], "failures": r["failures"],
            "success_rate": round(1 - (r["failures"] or 0) / r["n"], 4) if r["n"] else None,
            "avg_duration_ms": round(r["avg_ms"] or 0, 1),
            "input_tokens": r["tin"] or 0, "output_tokens": r["tout"] or 0,
        } for r in rows]}


class _AdvisoryLock:
    """Reusable ``with`` lock: a thread lock plus a Postgres session advisory lock held on a
    dedicated pooled connection for the duration of the block."""

    def __init__(self, store: "PostgresStore", name: str) -> None:
        import zlib
        self.store = store
        self.key = zlib.crc32(name.encode()) & 0x7FFFFFFF
        self._local = threading.Lock()
        self._conn = None

    def __enter__(self):
        self._local.acquire()
        try:
            self._cm = self.store._pool.connection()
            self._conn = self._cm.__enter__()
            self._conn.execute("SELECT pg_advisory_lock(%s)", (self.key,))
        except BaseException:
            self._local.release()
            raise
        return self

    def __exit__(self, *exc):
        try:
            self._conn.execute("SELECT pg_advisory_unlock(%s)", (self.key,))
            self._cm.__exit__(None, None, None)
        finally:
            self._conn = None
            self._local.release()
        return False


def _loads(v: Any) -> Any:
    if v is None:
        return None
    if isinstance(v, (str, bytes)):
        return json.loads(v)
    return v


def _json_safe(v: Any) -> Any:
    """Round-trip through json so non-JSON values (datetimes, sets) become what SQLite stored.
    Postgres refuses NUL characters in text and JSONB, so they become U+FFFD."""
    text = json.dumps(v, default=str)
    if "\\u0000" in text:
        text = text.replace("\\u0000", "\\ufffd")
    return json.loads(text)


def _txt(v: Any) -> Any:
    return v.replace("\x00", "\ufffd") if isinstance(v, str) else v


def full_schema_sql() -> str:
    """Every table the server creates on Postgres, as one script (``deploy/sql/postgres.sql``)."""
    from .. import analytics, drift, incidents
    from ..enterprise import audit, pii, rbac
    from ..incidents import hooks
    parts = [
        "-- Tracedown: Postgres schema. Generated by `python -m tracedown_server.storage.postgres`;",
        "-- the server creates and migrates these tables itself on start, so applying this file is optional",
        "-- (useful for review, or for a DBA who provisions schemas ahead of time).",
        f"-- Schema version {SCHEMA_VERSION}. High-volume spans can live in ClickHouse instead (clickhouse.sql).",
        "",
        "-- core: runs, spans, payloads, findings",
        CORE_SCHEMA.strip(),
        f"INSERT INTO schema_migrations(version, note) VALUES ({SCHEMA_VERSION}, 'core tables') ON CONFLICT DO NOTHING;",
    ]
    for name, mod in (("settings (analytics)", analytics), ("drift", drift), ("incidents", incidents),
                      ("notification hooks", hooks), ("users, roles and API keys", rbac), ("audit log", audit),
                      ("PII policies", pii)):
        parts += ["", f"-- {name}", translate_ddl(mod.SCHEMA).strip()]
    return "\n".join(parts) + "\n"


if __name__ == "__main__":
    print(full_schema_sql(), end="")
